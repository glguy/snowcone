-- Write the expected parse of a server-notice fixture, using the
-- dashboard's parser as the reference.
--
--   snowcone tests/hub/tools/expect-snotes.lua FIXTURE.log FIXTURE.expected.lua
--
-- The result is a list with one entry per line: the parsed notice, or
-- false for a line the parser doesn't recognise.

local pretty = require 'pl.pretty'

local here = (arg and arg[0] or ''):match '^(.*)/[^/]*$' or '.'
local parse = dofile(here .. '/../../../dashboard/utils/parse_snote.lua')

local fixture, out_name = arg[1], arg[2]
assert(fixture and out_name, 'usage: expect-snotes.lua FIXTURE.log OUT.expected.lua')

local expected = {}
for line in io.lines(fixture) do
    if line ~= '' and line:sub(1, 1) ~= '#' then
        local msg = assert(snowcone.parse_irc(line), line)
        local time = msg.tags.time and msg.tags.time:match 'T(%d%d:%d%d:%d%d)'
        local body = msg[2]:match '^%*%*%* Notice %-%- (.*)$'
        table.insert(expected, body and parse(time, msg.source, body) or false)
    end
end

local out = assert(io.open(out_name, 'w'))
out:write('-- Generated by tests/hub/tools/expect-snotes.lua from the dashboard parser\n')
out:write('return ', pretty.write(expected), '\n')
out:close()
print('entries', #expected)
